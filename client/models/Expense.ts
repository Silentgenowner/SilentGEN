import mongoose, {
  Document,
  Model,
  Schema,
  Types,
} from "mongoose";

/*
|--------------------------------------------------------------------------
| PAYMENT MODE
|--------------------------------------------------------------------------
*/

export type ExpensePaymentMode =
  | "cash"
  | "bank"
  | "upi"
  | "card"
  | "cheque"
  | "other";

/*
|--------------------------------------------------------------------------
| GST TYPE
|--------------------------------------------------------------------------
*/

export type ExpenseGstType =
  | "intra_state"
  | "inter_state"
  | "none";

/*
|--------------------------------------------------------------------------
| EXPENSE STATUS
|--------------------------------------------------------------------------
*/

export type ExpenseStatus =
  | "active"
  | "cancelled";

/*
|--------------------------------------------------------------------------
| EXPENSE INTERFACE
|--------------------------------------------------------------------------
*/

export interface IExpense
  extends Document {
  expenseNumber: string;

  expenseDate: Date;

  category: string;

  description: string;

  vendorName: string;

  vendorLedgerId?:
    | Types.ObjectId
    | null;

  billNumber: string;

  gstNumber: string;

  gstType:
    ExpenseGstType;

  taxableAmount: number;

  gstRate: number;

  cgst: number;

  sgst: number;

  igst: number;

  totalGst: number;

  totalAmount: number;

  paymentMode:
    ExpensePaymentMode;

  expenseLedgerId:
    Types.ObjectId;

  paymentLedgerId:
    Types.ObjectId;

  notes: string;

  status:
    ExpenseStatus;

  accountingPosted: boolean;

  accountingTransactionIds:
    Types.ObjectId[];

  createdBy?:
    | Types.ObjectId
    | null;

  isDeleted: boolean;

  deletedAt?:
    | Date
    | null;

  createdAt: Date;

  updatedAt: Date;
}

/*
|--------------------------------------------------------------------------
| EXPENSE SCHEMA
|--------------------------------------------------------------------------
*/

const ExpenseSchema =
  new Schema<IExpense>(
    {
      /*
      |--------------------------------------------------------------------------
      | EXPENSE NUMBER
      |--------------------------------------------------------------------------
      */

      expenseNumber: {
        type: String,

        required: true,

        unique: true,

        trim: true,

        index: true,
      },

      /*
      |--------------------------------------------------------------------------
      | EXPENSE DATE
      |--------------------------------------------------------------------------
      */

      expenseDate: {
        type: Date,

        required: true,

        default: Date.now,

        index: true,
      },

      /*
      |--------------------------------------------------------------------------
      | CATEGORY
      |--------------------------------------------------------------------------
      */

      category: {
        type: String,

        required: true,

        trim: true,

        index: true,
      },

      /*
      |--------------------------------------------------------------------------
      | DESCRIPTION
      |--------------------------------------------------------------------------
      */

      description: {
        type: String,

        required: true,

        trim: true,
      },

      /*
      |--------------------------------------------------------------------------
      | VENDOR
      |--------------------------------------------------------------------------
      */

      vendorName: {
        type: String,

        trim: true,

        default: "",
      },

      vendorLedgerId: {
        type:
          Schema.Types.ObjectId,

        ref:
          "Ledger",

        default:
          null,
      },

      /*
      |--------------------------------------------------------------------------
      | BILL NUMBER
      |--------------------------------------------------------------------------
      */

      billNumber: {
        type: String,

        trim: true,

        default: "",
      },

      /*
      |--------------------------------------------------------------------------
      | GST NUMBER
      |--------------------------------------------------------------------------
      */

      gstNumber: {
        type: String,

        trim: true,

        uppercase: true,

        default: "",
      },

      /*
      |--------------------------------------------------------------------------
      | GST TYPE
      |--------------------------------------------------------------------------
      */

      gstType: {
        type: String,

        enum: [
          "intra_state",
          "inter_state",
          "none",
        ],

        default:
          "none",
      },

      /*
      |--------------------------------------------------------------------------
      | TAXABLE AMOUNT
      |--------------------------------------------------------------------------
      */

      taxableAmount: {
        type: Number,

        required: true,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | GST RATE
      |--------------------------------------------------------------------------
      */

      gstRate: {
        type: Number,

        min: 0,

        max: 100,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | CGST
      |--------------------------------------------------------------------------
      */

      cgst: {
        type: Number,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | SGST
      |--------------------------------------------------------------------------
      */

      sgst: {
        type: Number,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | IGST
      |--------------------------------------------------------------------------
      */

      igst: {
        type: Number,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | TOTAL GST
      |--------------------------------------------------------------------------
      */

      totalGst: {
        type: Number,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | TOTAL AMOUNT
      |--------------------------------------------------------------------------
      */

      totalAmount: {
        type: Number,

        required: true,

        min: 0,

        default: 0,
      },

      /*
      |--------------------------------------------------------------------------
      | PAYMENT MODE
      |--------------------------------------------------------------------------
      */

      paymentMode: {
        type: String,

        enum: [
          "cash",
          "bank",
          "upi",
          "card",
          "cheque",
          "other",
        ],

        default:
          "cash",
      },

      /*
      |--------------------------------------------------------------------------
      | EXPENSE LEDGER
      |--------------------------------------------------------------------------
      */

      expenseLedgerId: {
        type:
          Schema.Types.ObjectId,

        ref:
          "Ledger",

        required:
          true,

        index:
          true,
      },

      /*
      |--------------------------------------------------------------------------
      | PAYMENT LEDGER
      |--------------------------------------------------------------------------
      */

      paymentLedgerId: {
        type:
          Schema.Types.ObjectId,

        ref:
          "Ledger",

        required:
          true,

        index:
          true,
      },

      /*
      |--------------------------------------------------------------------------
      | NOTES
      |--------------------------------------------------------------------------
      */

      notes: {
        type: String,

        trim: true,

        default: "",
      },

      /*
      |--------------------------------------------------------------------------
      | STATUS
      |--------------------------------------------------------------------------
      */

      status: {
        type: String,

        enum: [
          "active",
          "cancelled",
        ],

        default:
          "active",

        index:
          true,
      },

      /*
      |--------------------------------------------------------------------------
      | ACCOUNTING POSTED
      |--------------------------------------------------------------------------
      */

      accountingPosted: {
        type: Boolean,

        default:
          false,

        index:
          true,
      },

      /*
      |--------------------------------------------------------------------------
      | ACCOUNTING TRANSACTIONS
      |--------------------------------------------------------------------------
      */

      accountingTransactionIds: [
        {
          type:
            Schema.Types.ObjectId,

          ref:
            "AccountTransaction",
        },
      ],

      /*
      |--------------------------------------------------------------------------
      | CREATED BY
      |--------------------------------------------------------------------------
      */

      createdBy: {
        type:
          Schema.Types.ObjectId,

        ref:
          "Admin",

        default:
          null,
      },

      /*
      |--------------------------------------------------------------------------
      | SOFT DELETE
      |--------------------------------------------------------------------------
      */

      isDeleted: {
        type: Boolean,

        default:
          false,

        index:
          true,
      },

      deletedAt: {
        type: Date,

        default:
          null,
      },
    },
    {
      timestamps:
        true,
    }
  );

/*
|--------------------------------------------------------------------------
| DATABASE INDEXES
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| CATEGORY + DATE
|--------------------------------------------------------------------------
|
| Expense category report + date filtering.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  category:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| STATUS + DATE
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  status:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| ACTIVE / DELETED + DATE
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  isDeleted:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| VENDOR + DATE
|--------------------------------------------------------------------------
|
| Vendor-wise expense history.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  vendorLedgerId:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| EXPENSE LEDGER + DATE
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  expenseLedgerId:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| PAYMENT LEDGER + DATE
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  paymentLedgerId:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| PAYMENT MODE + DATE
|--------------------------------------------------------------------------
|
| Cash / Bank / UPI / Card reports.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  paymentMode:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| GST NUMBER + DATE
|--------------------------------------------------------------------------
|
| Vendor GSTIN-wise CA reports.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  gstNumber:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| GST TYPE + DATE
|--------------------------------------------------------------------------
|
| Intra-state / Inter-state GST reports.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  gstType:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| GST RATE + DATE
|--------------------------------------------------------------------------
|
| GST rate-wise expense report.
|
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  gstRate:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| ACCOUNTING POSTED + DATE
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  accountingPosted:
    1,

  expenseDate:
    -1,
});

/*
|--------------------------------------------------------------------------
| BILL NUMBER
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  billNumber:
    1,
});

/*
|--------------------------------------------------------------------------
| CREATED AT
|--------------------------------------------------------------------------
*/

ExpenseSchema.index({
  createdAt:
    -1,
});

/*
|--------------------------------------------------------------------------
| MODEL
|--------------------------------------------------------------------------
*/

const Expense:
  Model<IExpense> =
  mongoose.models
    .Expense ||
  mongoose.model<IExpense>(
    "Expense",

    ExpenseSchema
  );

export default Expense;