/*
|--------------------------------------------------------------------------
| SIZE STOCK
|--------------------------------------------------------------------------
*/

export type SizeStock = {
  size: string;
  stock: number;
};

/*
|--------------------------------------------------------------------------
| PRODUCT 360 FRAME
|--------------------------------------------------------------------------
*/

export type Product360Frame = {
  angle: number;

  name?: string;

  url?: string;

  base64?: string;

  mimeType?: string;
};

/*
|--------------------------------------------------------------------------
| PRODUCT 360 DATA
|--------------------------------------------------------------------------
*/

export type Product360 = {
  enabled: boolean;

  frames: Product360Frame[];
};

/*
|--------------------------------------------------------------------------
| PRODUCT REEL VIDEO
|--------------------------------------------------------------------------
|
| Used for short reel-style product videos.
|
| Rules:
|
| - Maximum duration: 30 seconds
| - Video stored on Cloudinary
| - Poster is used before video starts loading
|
|--------------------------------------------------------------------------
*/

export type ProductReelVideo = {
  enabled: boolean;

  url: string;

  publicId: string;

  duration: number;

  poster: string;
};

/*
|--------------------------------------------------------------------------
| COLOR VARIANT
|--------------------------------------------------------------------------
|
| Every color can have:
|
| - normal product images
| - total stock
| - size-wise stock
| - legacy/manual 360 images
| - AI/Cloudinary 360 frames
|
|--------------------------------------------------------------------------
*/

export type ColorVariant = {
  color: string;

  /*
  |--------------------------------------------------------------------------
  | COLOR IMAGES
  |--------------------------------------------------------------------------
  */

  images?: string[];

  /*
  |--------------------------------------------------------------------------
  | COLOR TOTAL STOCK
  |--------------------------------------------------------------------------
  */

  stock?: number;

  /*
  |--------------------------------------------------------------------------
  | COLOR + SIZE STOCK
  |--------------------------------------------------------------------------
  */

  sizeStocks?: SizeStock[];

  /*
  |--------------------------------------------------------------------------
  | LEGACY / MANUAL 360
  |--------------------------------------------------------------------------
  */

  view360Images?: string[];

  /*
  |--------------------------------------------------------------------------
  | AI COLOR-WISE 360
  |--------------------------------------------------------------------------
  */

  product360?: Product360;
};

/*
|--------------------------------------------------------------------------
| PRODUCT STATUS
|--------------------------------------------------------------------------
*/

export type ProductStatus =
  | "Active"
  | "Draft"
  | "Out of Stock"
  | "Archived";

/*
|--------------------------------------------------------------------------
| PRODUCT
|--------------------------------------------------------------------------
*/

export type Product = {
  /*
  |--------------------------------------------------------------------------
  | ID
  |--------------------------------------------------------------------------
  */

  _id: string;

  /*
  |--------------------------------------------------------------------------
  | BASIC INFORMATION
  |--------------------------------------------------------------------------
  */

  sku: string;

  name: string;

  slug: string;

  category: string;

  subCategory?: string;

  brand?: string;

  /*
  |--------------------------------------------------------------------------
  | DESCRIPTION
  |--------------------------------------------------------------------------
  */

  shortDescription?: string;

  description?: string;

  /*
  |--------------------------------------------------------------------------
  | PRODUCT DETAILS
  |--------------------------------------------------------------------------
  */

  gender?: string;

  fabric?: string;

  fit?: string;

  gsm?: number;

  weight?: number;

  /*
  |--------------------------------------------------------------------------
  | PRICE
  |--------------------------------------------------------------------------
  */

  mrp: number;

  price: number;

  discount?: number;

  /*
  |--------------------------------------------------------------------------
  | TOTAL PRODUCT STOCK
  |--------------------------------------------------------------------------
  |
  | Priority:
  |
  | 1. colorVariants inventory
  | 2. global sizeStocks
  | 3. manual stock
  |
  |--------------------------------------------------------------------------
  */

  stock: number;

  lowStockLimit?: number;

  sold?: number;

  /*
  |--------------------------------------------------------------------------
  | GLOBAL SIZE-WISE STOCK
  |--------------------------------------------------------------------------
  */

  sizeStocks?: SizeStock[];

  /*
  |--------------------------------------------------------------------------
  | PRODUCT IMAGES
  |--------------------------------------------------------------------------
  */

  thumbnail: string;

  images?: string[];

  /*
  |--------------------------------------------------------------------------
  | PRODUCT REEL VIDEO
  |--------------------------------------------------------------------------
  */

  reelVideo?: ProductReelVideo;

  /*
  |--------------------------------------------------------------------------
  | LEGACY / MANUAL PRODUCT 360
  |--------------------------------------------------------------------------
  */

  view360Images?: string[];

  /*
  |--------------------------------------------------------------------------
  | SIZES
  |--------------------------------------------------------------------------
  */

  sizes?: string[];

  /*
  |--------------------------------------------------------------------------
  | COLORS
  |--------------------------------------------------------------------------
  */

  colors?: string[];

  /*
  |--------------------------------------------------------------------------
  | COLOR VARIANTS
  |--------------------------------------------------------------------------
  */

  colorVariants?: ColorVariant[];

  /*
  |--------------------------------------------------------------------------
  | MAIN AI / CLOUDINARY 360
  |--------------------------------------------------------------------------
  */

  product360?: Product360;

  /*
  |--------------------------------------------------------------------------
  | TAGS
  |--------------------------------------------------------------------------
  */

  tags?: string[];

  /*
  |--------------------------------------------------------------------------
  | SUGGESTED PRODUCTS
  |--------------------------------------------------------------------------
  */

  suggestedProductIds?: string[];

  /*
  |--------------------------------------------------------------------------
  | PRODUCT FLAGS
  |--------------------------------------------------------------------------
  */

  featured?: boolean;

  bestSeller?: boolean;

  newArrival?: boolean;

  trending?: boolean;

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status?: ProductStatus;

  sortOrder?: number;

  /*
  |--------------------------------------------------------------------------
  | REVIEWS
  |--------------------------------------------------------------------------
  */

  rating?: number;

  reviewCount?: number;

  /*
  |--------------------------------------------------------------------------
  | SOFT DELETE
  |--------------------------------------------------------------------------
  */

  isDeleted?: boolean;

  deletedAt?: string | null;

  deletedBy?: string | null;

  /*
  |--------------------------------------------------------------------------
  | SEO
  |--------------------------------------------------------------------------
  */

  seoTitle?: string;

  seoDescription?: string;

  /*
  |--------------------------------------------------------------------------
  | TIMESTAMPS
  |--------------------------------------------------------------------------
  */

  createdAt?: string;

  updatedAt?: string;
};

/*
|--------------------------------------------------------------------------
| PRODUCT LIST API RESPONSE
|--------------------------------------------------------------------------
*/

export type ProductListResponse = {
  success: boolean;

  message?: string;

  products: Product[];

  count?: number;

  filters?: {
    genders: string[];

    categories: string[];

    subCategories: string[];

    newArrivals: boolean;

    bestSellers: boolean;

    offers: boolean;

    trending: boolean;
  };

  pagination?: {
    page: number;

    limit: number;

    totalProducts: number;

    totalPages: number;
  };
};

/*
|--------------------------------------------------------------------------
| SINGLE PRODUCT API RESPONSE
|--------------------------------------------------------------------------
*/

export type ProductResponse = {
  success: boolean;

  message?: string;

  product?: Product;
};